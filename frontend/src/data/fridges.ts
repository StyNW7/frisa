import type { Fridge, FoodItem } from '@/types'
import { isoInDays } from '@/lib/utils'

/**
 * Seed inventory.
 *
 * Expiry is written as an offset in days so the demo reads correctly on any day
 * it is presented: "expires tomorrow" is always literally tomorrow.
 */
type FoodSeed = Omit<FoodItem, 'expiresAt' | 'addedAt' | 'initialQuantity'> & {
  /** Days from today until the item expires. */
  expiresIn: number
  /** Days ago the item was added to the fridge. */
  addedAgo: number
  initialQuantity?: number
}

function build(seeds: FoodSeed[]): FoodItem[] {
  return seeds.map(({ expiresIn, addedAgo, initialQuantity, ...rest }) => ({
    ...rest,
    initialQuantity: initialQuantity ?? rest.quantity,
    expiresAt: isoInDays(expiresIn),
    addedAt: isoInDays(-addedAgo),
  }))
}

